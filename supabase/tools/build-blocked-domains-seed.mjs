// Builds supabase/seed-blocked-email-domains.sql from supabase/blocked-email-domains.txt.
// Usage (from the repo root): node supabase/tools/build-blocked-domains-seed.mjs
// The output is safe to paste again after every update: it only adds domains
// (on conflict do nothing). To UNblock a domain, delete it by hand:
//   delete from public.blocked_email_domains where domain = 'example.org';
import fs from 'node:fs';

const SRC = 'supabase/blocked-email-domains.txt';
const OUT = 'supabase/seed-blocked-email-domains.sql';

const domains = [...new Set(
  fs.readFileSync(SRC, 'utf8')
    .split(/\r?\n/)
    .map((l) => l.trim().toLowerCase())
    .filter((l) => l && !l.startsWith('#')),
)].filter((d) => /^[a-z0-9.-]+\.[a-z0-9-]+$/.test(d)).sort();

const CHUNK = 500;
let sql = `-- Generated by supabase/tools/build-blocked-domains-seed.mjs from ${SRC}.\n`
  + `-- ${domains.length} domains. Safe to re-run (adds only new ones).\n`;
for (let i = 0; i < domains.length; i += CHUNK) {
  const values = domains.slice(i, i + CHUNK).map((d) => `('${d}')`).join(',\n');
  sql += `insert into public.blocked_email_domains (domain) values\n${values}\non conflict (domain) do nothing;\n`;
}
fs.writeFileSync(OUT, sql);
console.log(`${OUT}: ${domains.length} domains, ${sql.split('\n').length - 1} lines`);
