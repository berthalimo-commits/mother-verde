// Builds the paste-ready seed for public.blocked_email_domains from
// supabase/blocked-email-domains.txt, split into parts of at most 1,500 lines
// each (one INSERT per part), so each part fits comfortably in the Supabase
// SQL Editor.
//
// Usage (from the repo root): node supabase/tools/build-blocked-domains-seed.mjs
// Output: supabase/seed-blocked-email-domains/part-01.sql, part-02.sql, …
// Every part is independent and safe to paste again (on conflict do nothing).
// To UNblock a domain, delete it by hand:
//   delete from public.blocked_email_domains where domain = 'example.org';
import fs from 'node:fs';
import path from 'node:path';

const SRC = 'supabase/blocked-email-domains.txt';
const OUT_DIR = 'supabase/seed-blocked-email-domains';
const MAX_LINES = 1500;
// Each part = 3 header lines + "insert … values" + N value lines + "on conflict …".
const PER_PART = MAX_LINES - 5;

const domains = [...new Set(
  fs.readFileSync(SRC, 'utf8')
    .split(/\r?\n/)
    .map((l) => l.trim().toLowerCase())
    .filter((l) => l && !l.startsWith('#')),
)].filter((d) => /^[a-z0-9.-]+\.[a-z0-9-]+$/.test(d)).sort();

fs.rmSync(OUT_DIR, { recursive: true, force: true });
fs.mkdirSync(OUT_DIR, { recursive: true });
const parts = Math.ceil(domains.length / PER_PART);
for (let p = 0; p < parts; p++) {
  const slice = domains.slice(p * PER_PART, (p + 1) * PER_PART);
  const name = `part-${String(p + 1).padStart(2, '0')}.sql`;
  const sql = [
    `-- blocked_email_domains seed, part ${p + 1} of ${parts} (${slice.length} domains).`,
    `-- Generated by supabase/tools/build-blocked-domains-seed.mjs from ${SRC}.`,
    '-- Safe to paste again: only adds domains that are not there yet.',
    'insert into public.blocked_email_domains (domain) values',
    slice.map((d) => `('${d}')`).join(',\n'),
    'on conflict (domain) do nothing;',
  ].join('\n') + '\n';
  fs.writeFileSync(path.join(OUT_DIR, name), sql);
  console.log(`${name}: ${sql.split('\n').length - 1} lines, ${slice.length} domains, first ${slice[0]}, last ${slice[slice.length - 1]}`);
}
console.log(`total: ${domains.length} domains in ${parts} parts`);
